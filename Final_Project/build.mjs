// Build script: produces the three files the browser loads directly.
//
// 1. lang/iot.grammar      -> lang/iot.parser.js          (Lezer grammar compiler)
// 2. public/editor-entry.js -> public/vendor/editor.bundle.js  (CodeMirror 6 + lang/)
// 3. node_modules/drawflow -> public/vendor/drawflow.*    (vendored, no CDN)
//
// All three outputs are committed, because the app loads them as-is (AGENTS.md).
// Run after any change to lang/ or to the editor entry point:  npm run build

import { buildParserFile } from "@lezer/generator";
import * as esbuild from "esbuild";
import { existsSync } from "node:fs";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const at = (...parts) => join(root, ...parts);

// A task whose source does not exist yet is skipped rather than failing, so the
// build works at every point of the plan, not only once everything is in place.
async function task(name, source, run) {
  if (!existsSync(source)) {
    console.log(`- ${name}: skipped, ${source.replace(root + "/", "")} does not exist yet`);
    return;
  }
  await run();
  console.log(`✓ ${name}`);
}

await mkdir(at("public/vendor"), { recursive: true });

await task("grammar -> lang/iot.parser.js", at("lang/iot.grammar"), async () => {
  const grammar = await readFile(at("lang/iot.grammar"), "utf8");
  // The grammar names its external tokens and props; moduleStyle "es" keeps the
  // generated parser importable by both the browser bundle and the Node server.
  const { parser, terms } = buildParserFile(grammar, {
    fileName: at("lang/iot.grammar"),
    moduleStyle: "es",
  });
  const header =
    "// GENERATED by `npm run build` from lang/iot.grammar - do not edit by hand.\n";
  await writeFile(at("lang/iot.parser.js"), header + parser);
  await writeFile(at("lang/iot.terms.js"), header + terms);
});

await task("editor -> public/vendor/editor.bundle.js", at("public/editor-entry.js"), () =>
  esbuild.build({
    entryPoints: [at("public/editor-entry.js")],
    outfile: at("public/vendor/editor.bundle.js"),
    bundle: true,
    format: "iife",
    globalName: "AtlasEditor",
    target: "es2022",
    minify: true,
    sourcemap: false,
    legalComments: "none",
    banner: {
      js:
        "/* Bundled by `npm run build`: CodeMirror 6 (MIT) + Lezer (MIT) + this\n" +
        "   project's lang/ modules. Source: public/editor-entry.js. Do not edit. */",
    },
  }),
);

await task("vendor drawflow", at("node_modules/drawflow/dist/drawflow.min.js"), async () => {
  await copyFile(
    at("node_modules/drawflow/dist/drawflow.min.js"),
    at("public/vendor/drawflow.min.js"),
  );
  await copyFile(
    at("node_modules/drawflow/dist/drawflow.min.css"),
    at("public/vendor/drawflow.min.css"),
  );
});
